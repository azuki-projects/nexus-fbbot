import express from 'express';
import cors from 'cors';
import path from 'path';
import fs from 'fs';
import { fileURLToPath } from 'url';
import { createServer as createViteServer } from 'vite';
import { botManager } from './server/botManager.ts';
import { storage } from './server/storage.ts';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

async function startServer() {
  const app = express();
  const PORT = Number(process.env.PORT) || 3000;

  app.use(cors());
  app.use(express.json({ limit: '10mb' }));
  app.use(express.urlencoded({ extended: true, limit: '10mb' }));

  // --- API ROUTES ---

  // Bot Status
  app.get('/api/bot/status', (_req, res) => {
    res.json(botManager.getStatus());
  });

  // Bot Config
  app.get('/api/bot/config', (_req, res) => {
    res.json(storage.getConfig());
  });

  app.post('/api/bot/config', (req, res) => {
    try {
      const updated = storage.updateConfig(req.body);
      botManager.addLog('info', 'Bot configuration updated via Web Login.');
      res.json({ success: true, config: updated });
    } catch (err: any) {
      res.status(400).json({ success: false, error: err.message });
    }
  });

  // Start / Stop Bot
  app.post('/api/bot/start', async (_req, res) => {
    const result = await botManager.startBot();
    res.json(result);
  });

  app.post('/api/bot/stop', async (_req, res) => {
    const result = await botManager.stopBot();
    res.json(result);
  });

  // Commands List
  app.get('/api/bot/commands', (_req, res) => {
    const cmds = botManager.getCommandsList();
    res.json(cmds);
  });

  // Reload Commands
  app.post('/api/bot/reload-cmds', async (_req, res) => {
    await botManager.loadCommands();
    res.json({ success: true, count: botManager.commands.size });
  });

  // Users & Economy
  app.get('/api/bot/users', (_req, res) => {
    res.json(storage.getAllUsers());
  });

  app.patch('/api/bot/users/:uid', (req, res) => {
    try {
      const { uid } = req.params;
      const updated = storage.updateUser(uid, req.body);
      botManager.addLog('info', `Admin manually updated user ${updated.name} (${uid})`);
      res.json({ success: true, user: updated });
    } catch (err: any) {
      res.status(400).json({ success: false, error: err.message });
    }
  });

  // Message Simulator
  app.post('/api/bot/simulate', async (req, res) => {
    try {
      const { senderID, senderName, body, role } = req.body;
      if (!body) {
        return res.status(400).json({ error: 'Message body is required' });
      }
      const result = await botManager.simulateMessage({
        senderID: senderID || '100089234123456',
        senderName: senderName || 'Simulator User',
        body,
        role: (typeof role === 'number' && [0, 1, 2].includes(role)) ? (role as 0 | 1 | 2) : 0
      });
      res.json(result);
    } catch (err: any) {
      res.status(500).json({ error: err.message });
    }
  });

  // Logs
  app.get('/api/bot/logs', (req, res) => {
    const limit = parseInt(req.query.limit as string || '100', 10);
    res.json(botManager.getLogs(limit));
  });

  app.post('/api/bot/logs/clear', (_req, res) => {
    botManager.clearLogs();
    res.json({ success: true });
  });

  // Standalone bot index.js exporter
  app.get('/api/bot/standalone-code', (_req, res) => {
    const config = storage.getConfig();
    const standaloneScript = `/**
 * Standalone Facebook Bot Runner
 * Generated by Nexus FB-Bot Engine
 * Powered by @tas33n/ws3-fca
 */
const fs = require('fs');
const path = require('path');
const { login } = require('@tas33n/ws3-fca');

const config = JSON.parse(fs.readFileSync(path.join(__dirname, 'config.json'), 'utf-8'));
const usersFile = path.join(__dirname, 'data', 'users.json');

if (!fs.existsSync(path.join(__dirname, 'data'))) {
  fs.mkdirSync(path.join(__dirname, 'data'), { recursive: true });
}

let users = {};
try {
  if (fs.existsSync(usersFile)) {
    users = JSON.parse(fs.readFileSync(usersFile, 'utf-8'));
  }
} catch (e) {
  users = {};
}

function saveUsers() {
  fs.writeFileSync(usersFile, JSON.stringify(users, null, 2), 'utf-8');
}

console.log('Logging in to Facebook with AppState...');

login({ appState: config.appState }, config.loginOptions || {}, (err, api) => {
  if (err) {
    console.error('Login failed:', err);
    return;
  }

  const botUID = api.getCurrentUserID();
  console.log('✅ Bot is ONLINE! Logged in as UID:', botUID);
  console.log('Prefix:', config.prefix || '(none)');

  api.listenMqtt((err, event) => {
    if (err) return console.error('MQTT error:', err);
    if (!event || (event.type !== 'message' && event.type !== 'message_reply')) return;

    const body = (event.body || '').trim();
    if (!body) return;

    // Command matching logic
    console.log('[FB MESSAGE]', event.senderID, ':', body);
    if (body === (config.prefix + 'ping') || body === 'ping') {
      api.sendMessage('🏓 Pong! Bot is active and running cleanly.', event.threadID, event.messageID);
    }
  });
});
`;
    res.json({ code: standaloneScript, config });
  });

  // --- VITE MIDDLEWARE / STATIC SERVING ---
  const isProduction = process.env.NODE_ENV === 'production';
  const distPath = path.join(process.cwd(), 'dist');
  const hasDist = fs.existsSync(path.join(distPath, 'index.html'));

  if (!isProduction || !hasDist) {
    // If in development OR if dist was not pre-built on Render, compile on the fly with Vite
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa'
    });
    app.use(vite.middlewares);

    // Serve transformed frontend index.html for all non-API routes
    app.use('*', async (req, res, next) => {
      const url = req.originalUrl;
      if (url.startsWith('/api')) {
        return next();
      }
      try {
        let template = fs.readFileSync(path.resolve(process.cwd(), 'index.html'), 'utf-8');
        template = await vite.transformIndexHtml(url, template);
        res.status(200).set({ 'Content-Type': 'text/html' }).end(template);
      } catch (e: any) {
        if (typeof vite.ssrFixStacktrace === 'function') {
          vite.ssrFixStacktrace(e);
        }
        next(e);
      }
    });
  } else {
    // Pre-built production bundle
    app.use(express.static(distPath));
    app.get('*', (req, res, next) => {
      if (req.originalUrl.startsWith('/api')) return next();
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`[Server] Nexus FB-Bot Manager running on http://0.0.0.0:${PORT}`);
  });
}

startServer().catch((err) => {
  console.error('[Server] Fatal startup error:', err);
  process.exit(1);
});
